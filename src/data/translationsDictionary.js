/**
 * Universal bilingual extractor
 * Always returns { en: string, gu: string }
 */
export function getBilingualText(item) {
  if (!item) return { en: '', gu: '' };
  
  if (typeof item === 'object') {
    const en = item.en || item.title || item.name || '';
    let gu = item.gu || item.titleGujarati || item.gujarati || '';
    if (!gu && en) {
      const cleanEn = String(en).trim();
      gu = mergedDictionary[cleanEn] ||
           (cleanEn.endsWith('.') ? mergedDictionary[cleanEn.slice(0, -1).trim()] : mergedDictionary[cleanEn + '.']) ||
           '';
    }
    return { en: String(en), gu: String(gu) };
  }

  const str = String(item).trim();
  let gu = mergedDictionary[str] || '';
  if (!gu) {
    if (str.endsWith('.')) {
      gu = mergedDictionary[str.slice(0, -1).trim()] || '';
    } else {
      gu = mergedDictionary[str + '.'] || '';
    }
  }
  return { en: str, gu: gu };
}

